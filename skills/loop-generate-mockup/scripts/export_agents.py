#!/usr/bin/env python3
"""Export/check native agent profiles from shared Markdown (Python 3.11+).

Checks configuration drift only, not model availability, dispatch or runtime identity.
"""

import argparse
import json
from pathlib import Path
import sys
import tomllib


ROLES = {
    "builder": "Sole HTML mockup builder; owns mockup files and draft design brief.",
    "reviewer": "Independent rendered UI/UX mockup reviewer; no mockup or source edits.",
}
MARKER = "Generated by loop-generate-mockup/export_agents.py"


def render_profiles(root, harness, model, effort):
    profiles = {}
    for role, description in ROLES.items():
        name = f"loop-generate-mockup-{role}"
        instructions = (root / "agents" / f"{role}.md").read_text(encoding="utf-8").strip()
        instructions += f"\n\nRead required review.md/handoff.md from: {root / 'references'}\n"
        if harness == "codex":
            fields = {
                "name": name,
                "description": description,
                "model": model,
                "model_reasoning_effort": effort,
                "sandbox_mode": "workspace-write",
                "developer_instructions": instructions,
            }
            content = f"# {MARKER}\n" + "".join(
                f"{key} = {json.dumps(value, ensure_ascii=False)}\n"
                for key, value in fields.items()
            )
            if tomllib.loads(content) != fields:
                raise ValueError("Generated TOML did not round-trip")
            profiles[name + ".toml"] = content
        else:
            fields = {"description": description}
            if harness == "copilot":
                fields.update(name=name, model=model, modelPolicy="required", reasoningEffort=effort)
                suffix = ".agent.md"
            else:
                fields.update(mode="subagent")
                if harness == "opencode-v2":
                    fields["model"] = f"{model}#{effort}"
                else:
                    fields.update(model=model, reasoningEffort=effort)
                suffix = ".md"
            frontmatter = "".join(
                f"{key}: {json.dumps(value, ensure_ascii=False)}\n"
                for key, value in fields.items()
            )
            profiles[name + suffix] = (
                f"---\n{frontmatter}---\n\n<!-- {MARKER} -->\n\n{instructions}"
            )
    return profiles


def check_profiles(output, profiles):
    errors = []
    for name, expected in profiles.items():
        path = output / name
        if not path.is_file():
            errors.append(f"Missing profile: {path}")
        elif path.read_text(encoding="utf-8") != expected:
            errors.append(f"Profile drift: {path}")
    return errors


def write_profiles(output, profiles):
    # Validate both targets before writing either; preserve unmanaged definitions.
    for name in profiles:
        target = output / name
        if target.is_symlink():
            raise ValueError(f"Refusing to replace symlink: {target}")
        if target.exists():
            text = target.read_text(encoding="utf-8")
            if not (text.startswith(f"# {MARKER}\n") or f"\n<!-- {MARKER} -->\n" in text):
                raise ValueError(f"Refusing to replace unmanaged profile: {target}")
    output.mkdir(parents=True, exist_ok=True)
    for name, content in profiles.items():
        (output / name).write_text(content, encoding="utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--harness", choices=("codex", "copilot", "opencode", "opencode-v2"), required=True)
    parser.add_argument("--model", required=True, help="Verified model identifier in the target harness")
    parser.add_argument("--effort", required=True, help="Reasoning effort, or OpenCode V2 model variant")
    parser.add_argument("--output", type=Path, required=True, help="Exact native agent directory")
    action = parser.add_mutually_exclusive_group(required=True)
    action.add_argument("--check", action="store_true")
    action.add_argument("--write", action="store_true")
    args = parser.parse_args()
    if not args.model.strip() or not args.effort.strip():
        parser.error("Model and effort must be explicit nonempty values")
    if args.harness.startswith("opencode") and ("/" not in args.model or "#" in args.model):
        parser.error("OpenCode requires provider/model without a #variant; pass variant through --effort")
    root = Path(__file__).resolve().parent.parent
    try:
        profiles = render_profiles(root, args.harness, args.model, args.effort)
        if args.write:
            write_profiles(args.output, profiles)
        errors = check_profiles(args.output, profiles)
        if errors:
            print("\n".join(errors), file=sys.stderr)
            return 1
    except (OSError, ValueError) as error:
        print(str(error), file=sys.stderr)
        return 1
    print(f"Both {args.harness} profiles match canonical roles and supplied model/effort.")
    print("Model availability, effective overrides, dispatch and runtime identity are not verified.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
